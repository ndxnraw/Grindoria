import {spawn} from 'node:child_process';
import {mkdtempSync,readFileSync,mkdirSync} from 'node:fs';
import path from 'node:path';
import {root} from './lib/project.mjs';
mkdirSync(path.join(root,'work'),{recursive:true});
const data=mkdtempSync(path.join(root,'work/desktop-smoke-'));
const exe=path.join(root,'release/win-unpacked/Grindoria.exe');
const child=spawn(exe,[],{env:{...process.env,GRINDORIA_SMOKE_TEST:'1',GRINDORIA_USER_DATA_DIR:data},windowsHide:true,stdio:'inherit'});
const timeout=setTimeout(()=>child.kill(),45000);
child.on('error',error=>{clearTimeout(timeout);console.error(error.message);process.exitCode=1;});
child.on('exit',code=>{clearTimeout(timeout);try{const report=JSON.parse(readFileSync(path.join(data,'smoke-report.json'),'utf8'));if(code!==0||!report.ok||!report.packaged)throw Error(JSON.stringify(report));console.log(JSON.stringify(report,null,2));}catch(error){console.error(error.message);process.exitCode=1;}});
